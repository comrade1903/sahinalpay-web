#!/usr/bin/env node
/**
 * Writes src/archive/summary.generated.ts — everything the home page needs
 * about the archive, and nothing else.
 *
 * The home page shows four section counts and a coverage strip of per-outlet
 * year ranges. Getting those used to mean importing the whole archive index:
 * 468 kB raw / 115 kB gzip of every record's
 * metadata in both languages, downloaded by every first-time visitor before
 * the counts could appear. The summary carries the same numbers in a fraction
 * of that.
 *
 * Regenerate with `npm run generate:summary`; `npm run validate:content`
 * fails if the committed file is stale, and CI runs both.
 */
import fs from 'node:fs'
import path from 'node:path'
import { loadModule, projectRoot } from './lib/load-archive.mjs'

const dateUtils = await loadModule('src/dateUtils.ts', 'date-utils-summary.mjs')
const archive = await (await import('./lib/load-archive.mjs')).loadArchive()

function yearRange(group) {
  const years = group
    .map((item) => (item.date ? dateUtils.parseTurkishDate(item.date) : null))
    .filter((value) => value !== null)
    .map((ts) => new Date(ts).getUTCFullYear())
  if (!years.length) return null
  return { from: Math.min(...years), to: Math.max(...years) }
}

/* Same groups, in the same order, as CoverageStrip built by hand: every
   outlet in both languages, then academic articles as one row. */
const coverage = []
for (const group of [
  ...archive.archiveData.columns.tr,
  ...archive.archiveData.columns.en,
  ...archive.archiveData.analyses,
]) {
  const range = yearRange(group.items)
  if (!range) continue
  coverage.push({ outlet: group.outlet, ...range, count: group.items.length })
}
/* Both languages in one row: the page lists them together, under separate
   headings, and the coverage strip names the section rather than an outlet. */
const academicItems = [
  ...archive.archiveData.academicArticles.tr,
  ...archive.archiveData.academicArticles.en,
]
const academicRange = yearRange(academicItems)
if (academicRange) {
  coverage.push({ academic: true, ...academicRange, count: academicItems.length })
}

const counts = {
  columns: {
    tr: archive.archiveData.columns.tr.reduce((sum, group) => sum + group.items.length, 0),
    en: archive.archiveData.columns.en.reduce((sum, group) => sum + group.items.length, 0),
  },
  analyses: archive.archiveData.analyses.reduce((sum, group) => sum + group.items.length, 0),
  interviews: archive.archiveData.interviews.length,
  academic: academicItems.length,
}

const source = `/* GENERATED by scripts/generate-archive-summary.mjs — do not edit.
   Run \`npm run generate:summary\` after changing archive data.

   The home page imports this instead of the full archive index so a first
   visit does not download every record's metadata in both languages. */

import type { ArchiveLang } from './types'

export interface CoverageBand {
  /** Display name of the outlet. Absent on the academic row, whose label is
   *  translated in the UI like any other string. */
  outlet?: string
  academic?: boolean
  from: number
  to: number
  count: number
}

export interface ArchiveSummary {
  counts: {
    columns: Record<ArchiveLang, number>
    analyses: number
    interviews: number
    academic: number
  }
  coverage: CoverageBand[]
}

export const archiveSummary: ArchiveSummary = ${JSON.stringify(
  { counts, coverage },
  null,
  2,
)}
`

const target = path.join(projectRoot, 'src/archive/summary.generated.ts')
fs.writeFileSync(target, source)
console.log(`Wrote src/archive/summary.generated.ts (${coverage.length} coverage bands).`)
